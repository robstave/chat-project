"""OpenTelemetry setup for metrics, traces, and logs.

This module initializes OTel providers and exposes helpers used by commands
and config-level token logging.
"""

import logging
import os
import time
from functools import wraps

from opentelemetry import metrics
from opentelemetry import trace
from opentelemetry.metrics import Observation
from opentelemetry._logs import set_logger_provider
from opentelemetry.exporter.otlp.proto.http._log_exporter import OTLPLogExporter
from opentelemetry.exporter.otlp.proto.http.metric_exporter import OTLPMetricExporter
from opentelemetry.exporter.otlp.proto.http.trace_exporter import OTLPSpanExporter
from opentelemetry.sdk._logs import LoggerProvider, LoggingHandler
from opentelemetry.sdk._logs.export import BatchLogRecordProcessor
from opentelemetry.sdk.metrics import MeterProvider
from opentelemetry.sdk.metrics.export import PeriodicExportingMetricReader
from opentelemetry.sdk.resources import Resource
from opentelemetry.sdk.trace import TracerProvider
from opentelemetry.sdk.trace.export import BatchSpanProcessor


def _default_otlp_endpoint() -> str:
    """Choose a sane OTLP default for local and containerized runs."""
    if os.path.exists("/.dockerenv"):
        return "http://host.docker.internal:4318"
    return "http://127.0.0.1:4318"


_OTLP_ENDPOINT = os.environ.get("OTEL_EXPORTER_OTLP_ENDPOINT", _default_otlp_endpoint())

_resource = Resource.create({"service.name": "ducky-bot"})
_metric_exporter = OTLPMetricExporter(endpoint=f"{_OTLP_ENDPOINT}/v1/metrics")
_metric_reader = PeriodicExportingMetricReader(_metric_exporter, export_interval_millis=15000)
_metric_provider = MeterProvider(resource=_resource, metric_readers=[_metric_reader])
metrics.set_meter_provider(_metric_provider)

_tracer_provider = TracerProvider(resource=_resource)
_tracer_provider.add_span_processor(
    BatchSpanProcessor(OTLPSpanExporter(endpoint=f"{_OTLP_ENDPOINT}/v1/traces"))
)
trace.set_tracer_provider(_tracer_provider)

_otel_logger_provider = LoggerProvider(resource=_resource)
_otel_logger_provider.add_log_record_processor(
    BatchLogRecordProcessor(OTLPLogExporter(endpoint=f"{_OTLP_ENDPOINT}/v1/logs"))
)
set_logger_provider(_otel_logger_provider)

_root_logger = logging.getLogger()
if not any(getattr(handler, "_ducky_otel_handler", False) for handler in _root_logger.handlers):
    _log_handler = LoggingHandler(level=logging.INFO, logger_provider=_otel_logger_provider)
    _log_handler._ducky_otel_handler = True
    _root_logger.addHandler(_log_handler)

_meter = metrics.get_meter("ducky-bot")
_tracer = trace.get_tracer("ducky-bot")
_entry_logger = logging.getLogger("ducky.entrypoint")

command_counter = _meter.create_counter(
    "ducky_bot_commands_total",
    description="Number of times a command was invoked",
)
command_duration = _meter.create_histogram(
    "ducky_bot_command_duration_seconds",
    description="Time spent handling a command",
    unit="s",
)
llm_calls_total = _meter.create_counter(
    "ducky_bot_llm_calls_total",
    description="Number of LLM calls by command and model",
)
llm_tokens_total = _meter.create_counter(
    "ducky_bot_llm_tokens_total",
    description="LLM token usage by command, model, and token type",
)
_random_last_value: int | None = None


def _observe_random_last_value(_options):
    if _random_last_value is None:
        return []
    return [Observation(_random_last_value)]


random_last_value = _meter.create_observable_gauge(
    "ducky_bot_random_last_value",
    callbacks=[_observe_random_last_value],
    description="Last random number generated by the /random command",
)


def record_llm_usage(command: str, model: str, input_tokens: int, output_tokens: int, total_tokens: int) -> None:
    """Record model call and token totals as OTel metrics."""
    attrs = {"command": command, "model": model}
    llm_calls_total.add(1, attrs)
    llm_tokens_total.add(input_tokens, {**attrs, "token_type": "input"})
    llm_tokens_total.add(output_tokens, {**attrs, "token_type": "output"})
    llm_tokens_total.add(total_tokens, {**attrs, "token_type": "total"})


def record_random_result(result: int) -> None:
    """Expose the last generated random number as a gauge value."""
    global _random_last_value
    _random_last_value = result


def track_command(name: str):
    """Decorator that records invocation count and duration for a command handler."""

    def decorator(handler):
        @wraps(handler)
        async def wrapper(update, context):
            start = time.perf_counter()
            status = "ok"
            user = update.effective_user if update else None
            chat = update.effective_chat if update else None
            message = update.effective_message if update else None
            user_id = str(user.id) if user and user.id else "unknown"
            username = user.username if user and user.username else "unknown"
            chat_id = str(chat.id) if chat and chat.id else "unknown"
            text = message.text if message and message.text else ""

            _entry_logger.info(
                "command.entry command=%s user_id=%s username=%s chat_id=%s text=%r",
                name,
                user_id,
                username,
                chat_id,
                text,
            )

            with _tracer.start_as_current_span(f"command.{name}") as span:
                span.set_attribute("ducky.command", name)
                if user and user.id:
                    span.set_attribute("enduser.id", str(user.id))
                if user and user.username:
                    span.set_attribute("enduser.username", user.username)
                try:
                    return await handler(update, context)
                except Exception:
                    status = "error"
                    raise
                finally:
                    duration = time.perf_counter() - start
                    attrs = {"command": name, "status": status}
                    command_counter.add(1, attrs)
                    command_duration.record(duration, {"command": name})
                    span.set_attribute("ducky.status", status)
                    span.set_attribute("ducky.duration_seconds", duration)
                    _entry_logger.info(
                        "command.exit command=%s status=%s duration_seconds=%.6f user_id=%s username=%s chat_id=%s",
                        name,
                        status,
                        duration,
                        user_id,
                        username,
                        chat_id,
                    )

        return wrapper

    return decorator
